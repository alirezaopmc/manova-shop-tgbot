package crypto

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"crypto/sha256"
	"encoding/base64"
	"errors"
	"fmt"
	"io"
	"strings"
)

// DeriveKey derives a 32-byte key from kek using SHA-256.
func DeriveKey(kek string) []byte {
	h := sha256.Sum256([]byte(kek))
	return h[:]
}

// Encrypt encrypts plaintext using AES-256-GCM and a key derived from kek.
// When kek is empty, it returns the plaintext directly (for dev/test environments without KEK configured).
// The returned string is formatted as base64(nonce):base64(ciphertext+tag).
func Encrypt(plaintext string, kek string) (string, error) {
	if kek == "" {
		return plaintext, nil
	}
	if plaintext == "" {
		return "", nil
	}

	key := DeriveKey(kek)
	block, err := aes.NewCipher(key)
	if err != nil {
		return "", fmt.Errorf("crypto: create cipher: %w", err)
	}

	gcm, err := cipher.NewGCM(block)
	if err != nil {
		return "", fmt.Errorf("crypto: create gcm: %w", err)
	}

	nonce := make([]byte, gcm.NonceSize())
	if _, err := io.ReadFull(rand.Reader, nonce); err != nil {
		return "", fmt.Errorf("crypto: generate nonce: %w", err)
	}

	sealed := gcm.Seal(nil, nonce, []byte(plaintext), nil)
	return fmt.Sprintf("%s:%s", base64.StdEncoding.EncodeToString(nonce), base64.StdEncoding.EncodeToString(sealed)), nil
}

// Decrypt decrypts a ciphertext generated by Encrypt using kek.
// When kek is empty, it returns the ciphertext directly.
func Decrypt(ciphertext string, kek string) (string, error) {
	if kek == "" {
		return ciphertext, nil
	}
	if ciphertext == "" {
		return "", nil
	}

	key := DeriveKey(kek)
	block, err := aes.NewCipher(key)
	if err != nil {
		return "", fmt.Errorf("crypto: create cipher: %w", err)
	}

	gcm, err := cipher.NewGCM(block)
	if err != nil {
		return "", fmt.Errorf("crypto: create gcm: %w", err)
	}

	var nonce, encrypted []byte
	if strings.Contains(ciphertext, ":") {
		parts := strings.SplitN(ciphertext, ":", 2)
		var err error
		nonce, err = base64.StdEncoding.DecodeString(parts[0])
		if err != nil {
			return "", fmt.Errorf("crypto: decode nonce: %w", err)
		}
		encrypted, err = base64.StdEncoding.DecodeString(parts[1])
		if err != nil {
			return "", fmt.Errorf("crypto: decode ciphertext: %w", err)
		}
	} else {
		data, err := base64.StdEncoding.DecodeString(ciphertext)
		if err != nil {
			return "", fmt.Errorf("crypto: decode ciphertext: %w", err)
		}
		if len(data) < gcm.NonceSize() {
			return "", errors.New("crypto: ciphertext too short")
		}
		nonce = data[:gcm.NonceSize()]
		encrypted = data[gcm.NonceSize():]
	}

	if len(nonce) != gcm.NonceSize() {
		return "", fmt.Errorf("crypto: invalid nonce size %d", len(nonce))
	}

	plain, err := gcm.Open(nil, nonce, encrypted, nil)
	if err != nil {
		return "", fmt.Errorf("crypto: decrypt failed: %w", err)
	}

	return string(plain), nil
}
